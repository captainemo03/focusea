const fs = require('fs');
const vm = require('vm');
const assert = require('assert/strict');
const source = fs.readFileSync('decision-lab-pro.js', 'utf8');
const context = {};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function estimate('), source.indexOf('function stressCases(')), context);
const input = {speed:10,distance:2400,port_days:2,sea_cons:20,bunker_price:500,cargo_qty:10000,freight_rate:50,commission:2,laycan_buffer:3,delay_cost:1000,port_costs:20000,canal_costs:10000,daily_hire:10000};
const result = context.estimate(input);
assert.equal(result.gross_revenue,500000);
assert.equal(result.bunker_cost,104000);
assert.equal(result.hire_cost,120000);
assert.equal(result.net_profit,236000);
assert.equal(result.tce,29667);
const expensiveHire = context.estimate({...input,daily_hire:20000});
assert.equal(expensiveHire.tce,result.tce,'Changing hire must not change TCE');
assert.equal(expensiveHire.net_profit,result.net_profit-120000);
assert.equal(context.estimate(input,10,0,5).delay_exposure,2000);
console.log('Decision economics passed: TCE, hire, revenue and delay exposure.');
